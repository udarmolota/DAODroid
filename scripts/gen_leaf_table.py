#!/usr/bin/env python3
"""Writes the harness's function table from find_leaf_funcs.py's CSV: a header with
PPC_EXTERN_FUNC declarations and a {name, pointer} array of the chosen leaf functions.

    python -I scripts/gen_leaf_table.py <leaf_funcs.csv> <out.inc> [--vmx N] [--other M]

Takes the N largest VMX/FP leaf functions and the M largest integer-only ones (defaults 300
and 100). The output is generated from the game's function addresses, so it goes to build/,
not into git. Read-only on its inputs.
"""
import argparse
import csv
import re
import sys
from pathlib import Path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("csv")
    ap.add_argument("out")
    ap.add_argument("--vmx", type=int, default=300)
    ap.add_argument("--other", type=int, default=100)
    ap.add_argument("--mem", type=int, default=200,
                    help="call-free VMX/FP functions that touch guest memory (run only when the harness maps a guest space)")
    ap.add_argument("--imports", help="also write stubs for every kernel import the generated code declares "
                                      "(PPC_EXTERN_FUNC(__imp__X) in ppc_recomp_shared.h) to this file")
    ap.add_argument("--shared", default=str(Path(__file__).resolve().parent.parent / "recomp" / "ppc" / "ppc_recomp_shared.h"))
    args = ap.parse_args()

    if args.imports:
        names = []
        with open(args.shared, encoding="utf-8") as f:
            for line in f:
                m = re.match(r"PPC_EXTERN_FUNC\(__imp__(?!sub_)(\w+)\);", line)
                if m:
                    names.append(m.group(1))
        with open(args.imports, "w", encoding="utf-8", newline="\n") as f:
            f.write("// Generated by scripts/gen_leaf_table.py: the kernel imports the generated code links\n")
            f.write("// against. Leaf functions never reach them; any call is a harness bug.\n")
            for n in names:
                f.write(f"PPC_FUNC(__imp__{n}) {{ (void)ctx; (void)base; std::abort(); }}\n")
        print(f"{len(names)} import stubs -> {args.imports}")

    with open(args.csv, encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    rows.sort(key=lambda r: -int(r["instructions"]))
    pure = [r for r in rows if r.get("memory", "0") == "0"]
    vmx = [r for r in pure if r["vmx_or_fp"] == "1"][:args.vmx]
    other = [r for r in pure if r["vmx_or_fp"] == "0"][:args.other]
    # Memory-touching functions run on a zeroed guest space: a loop there may never end, so
    # only loop-free ones are taken.
    mem = [r for r in rows if r.get("memory", "0") == "1" and r["vmx_or_fp"] == "1"
           and r.get("loop", "0") == "0"][:args.mem]
    chosen = vmx + other + mem
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by scripts/gen_leaf_table.py: leaf functions for the ARM64/x64 harness.\n")
        f.write(f"// {len(vmx)} with VMX/FP work, {len(other)} integer-only, {len(mem)} VMX/FP with guest memory access.\n")
        # The implementations themselves (__imp__sub_X, extern "C"), not the weak sub_X aliases
        # the generated code calls through: the harness must not depend on how the host's
        # linker resolves weak aliases.
        for r in chosen:
            f.write(f"extern \"C\" PPC_FUNC(__imp__{r['function']});\n")
        f.write("\nstatic const LeafFunc kLeafFuncs[] = {\n")
        for r in chosen:
            f.write(f"    {{ \"{r['function']}\", __imp__{r['function']}, {r['instructions']}, {r['vmx_or_fp']}, {r.get('memory', '0')} }},\n")
        f.write("};\n")
    print(f"{len(chosen)} functions -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
